#!/usr/bin/env python3
"""Extract vanilla GUI sprites and their nine-slice metadata for the HTML port.

Minecraft 26.3 has no assets/minecraft/gui/*.json layouts: the layouts live in the
client bytecode. The sprites *do* ship with JSON metadata, and that metadata is the
real source of truth for how a sprite is sliced/stretched. This script copies every
sprite the port uses and generates web/ui/sprites/sprites.css from the .mcmeta files.

usage: scripts/gen_gui_sprites.py [--jar PATH] [--out DIR]
"""
import argparse
import json
import os
import zipfile

DEFAULT_JAR = os.path.expanduser(
    '~/Library/Application Support/minecraft/versions/26.3/26.3.jar')

SPRITES = [
    # buttons
    'widget/button', 'widget/button_highlighted', 'widget/button_disabled',
    # fields, tabs, checkboxes, sliders, scrollbars
    'widget/text_field', 'widget/text_field_highlighted',
    'widget/tab', 'widget/tab_highlighted',
    'widget/tab_selected', 'widget/tab_selected_highlighted',
    'widget/checkbox', 'widget/checkbox_highlighted',
    'widget/checkbox_selected', 'widget/checkbox_selected_highlighted',
    'widget/slider', 'widget/slider_highlighted',
    'widget/slider_handle', 'widget/slider_handle_highlighted',
    'widget/scroller', 'widget/scroller_background',
    'widget/slot_frame',
    # icons
    'icon/language', 'icon/accessibility', 'icon/checkmark', 'icon/info',
    'icon/search', 'icon/unseen_notification',
    'pause_menu/bug', 'pause_menu/social_interactions', 'pause_menu/player_reporting',
    # panels
    'popup/background', 'dialog/warning_button', 'dialog/warning_button_highlighted',
    'dialog/warning_button_disabled',
    # world list (Select World screen)
    'world_list/error', 'world_list/error_highlighted',
    'world_list/join', 'world_list/join_highlighted',
    'world_list/marked_join', 'world_list/marked_join_highlighted',
    'world_list/warning', 'world_list/warning_highlighted',
    # server list icons (reused for world list diagnostics)
    'server_list/incompatible', 'server_list/unreachable',
    # tooltips
    'tooltip/background', 'tooltip/frame',
    # misc icons used by the world screens
    'icon/news', 'icon/link', 'icon/link_highlighted',
    'icon/music_notes', 'icon/video_link', 'icon/video_link_highlighted',
    'gamemode_switcher/slot', 'gamemode_switcher/selection',
    'transferable_list/select', 'transferable_list/unselect',
]


def border_of(meta):
    scaling = ((meta or {}).get('gui') or {}).get('scaling') or {}
    if scaling.get('type') != 'nine_slice':
        return None
    border = scaling.get('border', 0)
    if isinstance(border, int):
        return (border, border, border, border)
    return (border.get('top', 0), border.get('right', 0),
            border.get('bottom', 0), border.get('left', 0))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--jar', default=DEFAULT_JAR)
    ap.add_argument('--out', default='web/ui/sprites')
    args = ap.parse_args()

    if not os.path.isfile(args.jar):
        raise SystemExit('missing client jar: ' + args.jar)
    os.makedirs(args.out, exist_ok=True)

    manifest = {}
    lines = [
        '/* Generated by scripts/gen_gui_sprites.py from the real 26.3 client jar. */',
        '.mc-sprite { image-rendering: pixelated; background: none; }',
        '',
    ]
    with zipfile.ZipFile(args.jar) as jar:
        for name in SPRITES:
            base = 'assets/minecraft/textures/gui/sprites/' + name
            try:
                png = jar.read(base + '.png')
            except KeyError:
                print('warning: missing sprite', name)
                continue
            dst = os.path.join(args.out, name + '.png')
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            with open(dst, 'wb') as f:
                f.write(png)

            meta = None
            try:
                meta = json.loads(jar.read(base + '.png.mcmeta'))
            except KeyError:
                pass
            manifest[name] = {'meta': meta}
            cls = 'sprite-' + name.replace('/', '-')
            url = "url('%s.png')" % name
            border = border_of(meta)
            if border is None:
                lines.append('.%s { %s background-size: 100%% 100%%; image-rendering: pixelated; }'
                             % (cls, 'background-image: ' + url + ';'))
            else:
                top, right, bottom, left = border
                lines.append(
                    '.%s { border-style: solid; border-width: %dpx %dpx %dpx %dpx;'
                    ' border-image: %s %d %d %d %d fill / %dpx %dpx %dpx %dpx stretch;'
                    ' image-rendering: pixelated; background: none; }'
                    % (cls, top, right, bottom, left, url,
                       top, right, bottom, left, top, right, bottom, left))
    with open(os.path.join(args.out, 'sprites.css'), 'w') as f:
        f.write('\n'.join(lines) + '\n')
    with open(os.path.join(args.out, 'manifest.json'), 'w') as f:
        json.dump(manifest, f, indent=2, sort_keys=True)
    print('wrote', os.path.join(args.out, 'sprites.css'), 'and', len(manifest), 'sprites')


if __name__ == '__main__':
    main()
