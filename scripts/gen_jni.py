#!/usr/bin/env python3
"""Generates src/compat/java/org/lwjgl/system/JNI.java: the browser replacement of LWJGL's JNI class.

LWJGL calls every native function as JNI.invoke<sig>(args..., functionAddress). In the browser a
"function address" is an index into the JS function table __mcNative.fn (web/native/natives.js), so each
overload simply calls that JS function. Pointers / 64-bit integers cross as JS numbers (< 2^53).

usage: scripts/gen_jni.py <lwjgl.jar> <javap>
"""
import re
import subprocess
import sys

jar, javap = sys.argv[1], sys.argv[2]
out = subprocess.run([javap, "-cp", jar, "org.lwjgl.system.JNI"], check=True, capture_output=True, text=True).stdout

decl = re.compile(r"public static native (\w+) (\w+)\(([^)]*)\);")
JS_PARAM = {"long": "double", "boolean": "boolean", "byte": "int", "short": "int", "char": "int", "int": "int",
            "float": "float", "double": "double"}

lines = [
    "package org.lwjgl.system;",
    "",
    "import org.teavm.jso.JSBody;",
    "",
    "/** GENERATED by scripts/gen_jni.py - browser dispatch of LWJGL native calls to web/native/natives.js. */",
    "@SuppressWarnings(\"unused\")",
    "public final class JNI {",
    "    private JNI() {",
    "    }",
    "",
]
n = 0
for m in decl.finditer(out):
    ret, name, params = m.group(1), m.group(2), [p.strip() for p in m.group(3).split(",") if p.strip()]
    # last parameter is always the function address
    names = [f"a{i}" for i in range(len(params) - 1)] + ["fn"]
    jparams = ", ".join(f"{t} {nm}" for t, nm in zip(params, names))
    js_types = [("double" if t.endswith("[]") else JS_PARAM[t]) for t in params[:-1]] + ["int"]
    nparams = ", ".join(f"{t} {nm}" for t, nm in zip(js_types, names))
    call_args = []
    arrays = []
    for t, nm in zip(params[:-1], names[:-1]):
        if t.endswith("[]"):
            arrays.append(nm)
            call_args.append(f"(double) p_{nm}")
        else:
            call_args.append(f"(double) {nm}" if t == "long" else nm)
    call_args.append("(int) fn")
    js_args = ", ".join(names[:-1])
    call = f"__mcNative.fn[fn]({js_args})"
    nret = {"long": "double", "void": "void", "boolean": "boolean", "byte": "int", "short": "int", "char": "int",
            "int": "int", "float": "float", "double": "double"}[ret]
    if ret == "void":
        script = f"{call};"
    elif ret == "boolean":
        script = f"return !!{call};"
    elif ret in ("int", "byte", "short", "char"):
        script = f"return {call} | 0;"
    else:
        script = f"return +{call};"
    jsnames = ", ".join(f'"{nm}"' for nm in names)
    lines.append(f'    @JSBody(params = {{{jsnames}}}, script = "{script}")')
    lines.append(f"    private static native {nret} n{n}({nparams});")
    body_call = f"n{n}({', '.join(call_args)})"
    if ret == "void":
        body = f"{body_call};"
    elif ret == "long":
        body = f"return (long) {body_call};"
    elif ret in ("byte", "short", "char"):
        body = f"return ({ret}) {body_call};"
    else:
        body = f"return {body_call};"
    lines.append(f"    public static {ret} {name}({jparams}) {{")
    if arrays:
        # Java arrays are copied into the native heap for the call and copied back afterwards.
        for nm in arrays:
            lines.append(f"        long p_{nm} = mcport.lwjgl.NativeArrays.in({nm});")
        lines.append("        try {")
        lines.append(f"            {body}")
        lines.append("        } finally {")
        for nm in arrays:
            lines.append(f"            mcport.lwjgl.NativeArrays.out({nm}, p_{nm});")
        lines.append("        }")
    else:
        lines.append(f"        {body}")
    lines.append("    }")
    lines.append("")
    n += 1
lines.append("}")
path = "src/compat/java/org/lwjgl/system/JNI.java"
with open(path, "w") as f:
    f.write("\n".join(lines) + "\n")
print(f"{path}: {n} methods")
