import java.lang.reflect.Field;
import java.lang.reflect.Modifier;
import java.util.Map;
import java.util.TreeMap;

/**
 * Prints (as JS) the struct layouts and constants of LWJGL binding classes, as computed by LWJGL itself on a
 * 64-bit JVM. The browser natives (web/native/*.js) read and write structs at exactly these offsets.
 *
 * usage: java -cp lwjgl jars:build/tools DumpLwjglLayout <out.js> class...
 */
public class DumpLwjglLayout {
    public static void main(String[] args) throws Exception {
        StringBuilder js = new StringBuilder("// GENERATED by tools/src/DumpLwjglLayout.java from the LWJGL jars - do not edit.\n");
        js.append("var __mcLayout = {\n");
        for (int i = 1; i < args.length; i++) {
            Class<?> c = Class.forName(args[i], false, DumpLwjglLayout.class.getClassLoader());
            boolean struct = org.lwjgl.system.Struct.class.isAssignableFrom(c);
            if (struct) {
                // struct classes compute SIZEOF/ALIGNOF/<MEMBER> offsets in <clinit>
                Class.forName(args[i], true, DumpLwjglLayout.class.getClassLoader());
            }
            Map<String, Object> values = new TreeMap<>();
            for (Field f : c.getDeclaredFields()) {
                int m = f.getModifiers();
                if (!Modifier.isStatic(m) || !Modifier.isPublic(m) || !Modifier.isFinal(m)) {
                    continue;
                }
                Class<?> t = f.getType();
                if (t == int.class || t == long.class || t == short.class || t == byte.class) {
                    values.put(f.getName(), f.get(null));
                }
            }
            js.append("  '").append(c.getSimpleName()).append("': {");
            boolean first = true;
            for (Map.Entry<String, Object> e : values.entrySet()) {
                if (!first) {
                    js.append(", ");
                }
                first = false;
                Object v = e.getValue();
                String s = v instanceof Long ? Long.toString((Long) v) : v.toString();
                if (v instanceof Long && Math.abs((Long) v) > (1L << 53)) {
                    s = "'" + s + "'";
                }
                js.append(e.getKey()).append(": ").append(s);
            }
            js.append("},\n");
        }
        js.append("};\n");
        java.nio.file.Files.writeString(java.nio.file.Path.of(args[0]), js);
        System.out.println("wrote " + args[0]);
    }
}
